import type { Hazard, Level, Pickup, Platform, WorldId } from "./types";

const T = 32;

function plat(x: number, y: number, w: number, h: number, kind: Platform["kind"] = "solid"): Platform {
  return { x, y, w, h, kind, dx: 0, dy: 0 };
}

function mover(
  x: number,
  y: number,
  w: number,
  h: number,
  ax: number,
  ay: number,
  period: number,
  phase = 0,
): Platform {
  return {
    x,
    y,
    w,
    h,
    kind: "moving",
    dx: 0,
    dy: 0,
    move: { ox: x, oy: y, ax, ay, period, phase },
  };
}

function spikes(x: number, y: number, w: number): Hazard {
  return { kind: "spikes", x, y, w, h: 18 };
}

function lava(x: number, y: number, w: number, h: number): Hazard {
  return { kind: "lava", x, y, w, h };
}

function saw(x: number, y: number, r: number, ax = 0, ay = 0, period = 3, phase = 0): Hazard {
  return { kind: "saw", x, y, w: r * 2, h: r * 2, r, ox: x, oy: y, ax, ay, period, phase };
}

function fireball(x: number, y: number, vx: number, range: number): Hazard {
  return { kind: "fireball", x, y, w: 18, h: 18, vx, ox: x, oy: y, range };
}

function ice(x: number, y: number, w: number, h: number): Platform {
  return plat(x, y, w, h, "ice");
}

function icicle(x: number, y: number, w: number): Hazard {
  return { kind: "icicle", x, y, w, h: 22 };
}

function snake(x: number, y: number, range: number, period = 3.2, phase = 0): Hazard {
  return { kind: "snake", x, y, w: 58, h: 18, ox: x, oy: y, ax: range, period, phase };
}

function crab(x: number, y: number, range: number, period = 2.5): Hazard {
  return { kind: "crab", x, y, w: 22, h: 14, ox: x, oy: y, ax: range, period };
}

function llamaRide(
  x: number,
  y: number,
  w: number,
  h: number,
  ax: number,
  ay: number,
  period: number,
  phase = 0,
): Platform {
  const p = mover(x, y, w, h, ax, ay, period, phase);
  p.deco = "llama";
  return p;
}

function sealionRide(
  x: number,
  y: number,
  w: number,
  h: number,
  ax: number,
  ay: number,
  period: number,
  phase = 0,
): Platform {
  const p = mover(x, y, w, h, ax, ay, period, phase);
  p.deco = "sealion";
  return p;
}

function shark(x: number, y: number, range: number, period = 4.2, phase = 0): Hazard {
  return { kind: "shark", x, y, w: 86, h: 32, ox: x, oy: y, ax: range, period, phase };
}

function gold(x: number, y: number, w: number, h: number): Platform {
  return plat(x, y, w, h, "gold");
}

function crawlCover(x: number, floorTop: number, w: number): Platform {
  const gap = 30;
  const h = T * 2;
  return plat(x, floorTop - gap - h, w, h);
}

function squeezeCover(x: number, floorTop: number, w: number): Platform {
  const gap = 18;
  const h = T * 2;
  return plat(x, floorTop - gap - h, w, h);
}

function laser(x: number, y: number, w: number, h: number, period = 2.4, phase = 0): Hazard {
  return { kind: "laser", x, y, w, h, period, phase };
}

function rock(x: number, y: number, range: number, speed = 260, phase = 0, drift = 0): Hazard {
  return { kind: "rock", x, y, w: 22, h: 20, ox: x, oy: y, range, vx: speed, phase, ax: drift };
}

function coins(list: [number, number][], kind: Pickup["kind"] = "bean"): Pickup[] {
  return list.map(([x, y]) => ({
    x,
    y,
    r: kind === "fish" ? 14 : 12,
    taken: false,
    kind,
  }));
}

function arc(x: number, y: number, n: number, dx: number, lift: number): [number, number][] {
  const out: [number, number][] = [];
  for (let i = 0; i < n; i++) {
    const t = n === 1 ? 0 : i / (n - 1);
    out.push([x + i * dx, y - Math.sin(t * Math.PI) * lift]);
  }
  return out;
}

function make(
  id: string,
  world: WorldId,
  index: number,
  name: string,
  subtitle: string,
  width: number,
  height: number,
  spawnX: number,
  spawnY: number,
  platforms: Platform[],
  hazards: Hazard[],
  coinList: Pickup[],
  checks: { x: number; y: number; secret?: WorldId; returnTo?: WorldId; rideOx?: number; rideOy?: number }[],
  goal: { x: number; y: number },
  sky: string,
  tile: string,
  fog: string,
  waterline?: number,
  goalKind: Level["goalKind"] = "cacao",
  canSwim = false,
): Level {
  return {
    id,
    world,
    index,
    name,
    subtitle,
    width,
    height,
    spawnX,
    spawnY,
    platforms,
    hazards,
    coins: coinList,
    checkpoints: checks.map((c) => ({
      x: c.x,
      y: c.y,
      w: 36,
      h: 72,
      active: false,
      secret: c.secret,
      returnTo: c.returnTo,
      rideOx: c.rideOx,
      rideOy: c.rideOy,
    })),
    goal: {
      x: goal.x,
      y: goal.y,
      w: goalKind === "explorer" ? 52 : goalKind === "sol" ? 70 : 48,
      h: goalKind === "explorer" ? 78 : goalKind === "sol" ? 70 : 56,
      taken: false,
    },
    sky,
    tile,
    fog,
    waterline,
    goalKind,
    canSwim,
  };
}

