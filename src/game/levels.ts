function linkSecrets(levels: Level[]) {
  const PH = 42;
  const pairs: [WorldId, WorldId, { x: number; y: number; w: number; h: number }?][] = [
    ["amazonia", "cascada", { x: T * 71.2, y: T * 12, w: 28, h: T * 11 }],
    ["isabela", "fernandina", undefined],
    ["llamas", "pueblo", undefined],
    ["glaciar", "gruta", undefined],
    ["volcan", "risco", undefined],
  ];
  for (const [hostId, secretId, fall] of pairs) {
    const host = levels.find((l) => l.world === hostId);
    const secret = levels.find((l) => l.world === secretId);
    if (!host || !secret) continue;
    const pole = host.checkpoints.find((c) => c.secret === secretId);
    if (pole) secret.portal = { world: hostId, x: pole.x + 4, y: pole.y + pole.h - PH };
    if (fall) host.falls = [fall];
  }
}
